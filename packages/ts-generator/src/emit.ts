/**
 * generateTypeScript: SemanticIRDocument → deterministic TypeScript
 * sources. Consumes IR only; refuses invalid IR; byte-deterministic.
 */

import { compareByCodePoint, validateSemanticIR } from "@execspec/core";
import type { OperationIR, SemanticIRDocument, TypeDeclaration } from "@execspec/core";
import { emitTsTypes } from "./emit-types.js";
import { emitTsCodecs } from "./emit-codecs.js";
import { emitTsDispatcher, emitTsImplementationProtocol } from "./emit-dispatcher.js";

export interface GeneratedTsFile {
  readonly relativePath: string;
  readonly contents: string;
}

const HEADER = `// Generated by execspec. DO NOT EDIT.
`;

export function generateTypeScript(
  document: SemanticIRDocument,
  digest: string,
): readonly GeneratedTsFile[] {
  if (document.format !== "execspec" || document.irVersion !== 1) {
    throw new Error(`unsupported IR document: format=${String(document.format)} irVersion=${String(document.irVersion)}`);
  }
  const diagnostics = validateSemanticIR(document.semantic);
  if (diagnostics.length > 0) {
    const first = diagnostics[0];
    throw new Error(
      `refusing to generate TypeScript from invalid IR: ${first?.scope}: ${first?.code}: ${first?.message}`,
    );
  }

  const byId = <T extends { readonly id: string }>(items: readonly T[]): readonly T[] =>
    [...items].sort((left, right) => compareByCodePoint(left.id, right.id));
  const types = byId(document.semantic.types as readonly { id: string }[]) as readonly TypeDeclaration[];
  const operations = byId(document.semantic.operations) as readonly OperationIR[];
  const ir = { ...document.semantic, types, operations };

  return [
    {
      relativePath: "ExecSpecTypes.ts",
      contents: `${HEADER}\n${emitTsTypes(types)}`,
    },
    {
      relativePath: "ExecSpecImplementation.ts",
      contents: `${HEADER}\n${emitTsImplementationProtocol(ir, operations)}`,
    },
    {
      relativePath: "ExecSpecCodecs.ts",
      contents: `${HEADER}\n${emitTsCodecs(ir)}`,
    },
    {
      relativePath: "ExecSpecDispatcher.ts",
      contents: `${HEADER}\n${emitTsDispatcher(ir, digest, operations)}`,
    },
    {
      relativePath: "AGENTS.md",
      contents: GENERATED_AGENTS_MD,
    },
  ];
}

const GENERATED_AGENTS_MD = "# Generated by execspec. DO NOT EDIT.\n\nEverything in this directory is generated from the specification IR.\nHand edits are overwritten on the next regeneration.\n\n## Workflow\n\n1. Change the specification module, then compile it:\n   `execspec compile --module <spec>/dist/spec.js --out build/<name>.execspec.json`\n2. Regenerate this directory:\n   `execspec generate typescript --ir build/<name>.execspec.json --out <this directory>`\n   (from an execspec clone: `node packages/cli/dist/index.js ...`)\n3. Rebuild the host and run conformance:\n   `execspec test --ir build/<name>.execspec.json --host <host executable>`\n   Regeneration is deterministic: `git diff` after regenerating must be empty.\n\n## Rules\n\n- The specification digest is embedded in the dispatcher. A conformance\n  handshake failure saying \"digest mismatch\" means stale generated code\n  or a stale host build \u2014 regenerate and rebuild.\n- Business logic belongs in the handwritten implementation target, never\n  here. Implementations depend only on the generated types and protocol.\n- Domain failures are union values in operation outputs; `throws` is for\n  genuine implementation defects only.\n- TypeScript note: optional fields are absent keys \u2014 never assigned\n  `null` or `undefined`.";

