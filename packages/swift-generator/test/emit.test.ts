import { test } from "node:test";
import assert from "node:assert/strict";

import {
  structDeclaration,
  unionDeclaration,
  enumDeclaration,
  listType,
  refType,
  stringType,
  int64Type,
  booleanType,
  unitType,
} from "@execspec/core";
import {
  unionValue,
  listValue,
  int64Value,
} from "@execspec/core";
import type { OperationId, SemanticIR, SemanticIRDocument } from "@execspec/core";
import { generateSwift } from "../src/emit.js";

const DIGEST = "a".repeat(64);

function fixtureIR(order: "forward" | "reverse" = "forward"): SemanticIR {
  const types = [
    structDeclaration("PutRequest", [
      { name: "key", type: stringType(), optional: false },
      { name: "value", type: stringType(), optional: false },
    ]),
    structDeclaration("GetRequest", [{ name: "key", type: stringType(), optional: false }]),
    structDeclaration("Profile", [
      { name: "nickname", type: stringType(), optional: true },
      { name: "class", type: booleanType(), optional: false },
      { name: "aliases", type: listType(stringType()), optional: false },
    ]),
    unionDeclaration("GetResult", [
      { name: "found", payload: stringType() },
      { name: "missing", payload: unitType() },
      { name: "flagged", payload: booleanType() },
    ]),
    unionDeclaration("Nested", [
      { name: "items", payload: listType(listType(int64Type())) },
    ]),
    enumDeclaration("SortOrder", ["ascending", "descending"]),
  ];
  const operations = [
    {
      id: "kv.put" as OperationId,
      input: refType("PutRequest"),
      output: unitType(),
    },
    {
      id: "kv.get" as OperationId,
      input: refType("GetRequest"),
      output: refType("GetResult"),
    },
    {
      id: "kv.list" as OperationId,
      input: unitType(),
      output: listType(refType("GetResult")),
    },
    {
      id: "kv.echo" as OperationId,
      input: refType("Nested"),
      output: refType("Nested"),
    },
    {
      id: "kv.sort" as OperationId,
      input: refType("Profile"),
      output: refType("SortOrder"),
    },
  ];
  const scenarios = [
    {
      id: "kv.echo.roundtrip" as const,
      description: "echoes",
      steps: [
        {
          kind: "call" as const,
          binding: "echo",
          operationId: "kv.echo" as OperationId,
          input: {
            kind: "literal" as const,
            value: unionValue(
              "Nested",
              "items",
              listValue([listValue([int64Value(1n), int64Value(-2n)])]),
            ),
          },
        },
      ],
    },
  ];
  const flip = <T>(items: readonly T[]): readonly T[] =>
    order === "forward" ? items : [...items].reverse();
  return {
    specificationName: "kv",
    specificationVersion: "0.1.0",
    types: flip(types),
    operations: flip(operations),
    scenarios: scenarios as never,
  };
}

function documentFor(ir: SemanticIR): SemanticIRDocument {
  return { format: "execspec", irVersion: 1, semantic: ir, metadata: { sourceLocations: {} } };
}

test("generated files have the exact set of names and headers", () => {
  const files = generateSwift(documentFor(fixtureIR()), DIGEST);
  assert.deepEqual(
    files.map((file) => file.relativePath),
    [
      "ExecSpecTypes.swift",
      "ExecSpecImplementation.swift",
      "ExecSpecCodecs.swift",
      "ExecSpecDispatcher.swift",
      "AGENTS.md",
    ],
  );
  for (const file of files) {
    assert.ok(file.contents.endsWith("\n"), file.relativePath);
    if (file.relativePath.endsWith(".swift")) {
      assert.ok(file.contents.startsWith("// Generated by execspec. DO NOT EDIT.\n"), file.relativePath);
    }
  }
  const agents = files[4];
  assert.ok(agents !== undefined && agents.contents.startsWith("# Generated by execspec. DO NOT EDIT."));
  assert.ok(agents?.contents.includes("execspec generate swift"));
});

test("types emit exact Swift source", () => {
  const files = generateSwift(documentFor(fixtureIR()), DIGEST);
  const types = files[0];
  if (types === undefined) {
    throw new Error("missing types file");
  }
  assert.ok(types.contents.includes(`public struct ExecSpecUnit: Sendable {
    public init() {}
}`));
  assert.ok(types.contents.includes(`public struct PutRequest: Sendable {
    public let key: String
    public let value: String

    public init(
        key: String,
        value: String
    ) {
        self.key = key
        self.value = value
    }
}`));
  assert.ok(types.contents.includes(`public struct Profile: Sendable {
    public let nickname: String?
    public let class_: Bool
    public let aliases: [String]`));
  assert.ok(types.contents.includes(`public enum GetResult: Sendable {
    case found(String)
    case missing
    case flagged(Bool)
}`));
  assert.ok(types.contents.includes(`public enum SortOrder: Sendable {
    case ascending
    case descending
}`));
  assert.ok(!types.contents.includes("Codable"));
  assert.ok(!types.contents.includes("Equatable"));
});

test("implementation protocol emits exact Swift source", () => {
  const files = generateSwift(documentFor(fixtureIR()), DIGEST);
  const protocolFile = files[1];
  if (protocolFile === undefined) {
    throw new Error("missing protocol file");
  }
  assert.ok(protocolFile.contents.includes(
    `public protocol KVSpecificationImplementation: Sendable {
    func kvEcho(_ input: Nested) async throws -> Nested
    func kvGet(_ input: GetRequest) async throws -> GetResult
    func kvList(_ input: ExecSpecUnit) async throws -> [GetResult]
    func kvPut(_ input: PutRequest) async throws -> ExecSpecUnit
    func kvSort(_ input: Profile) async throws -> SortOrder
}`,
  ));
});

test("codecs emit exact union and int64 source", () => {
  const files = generateSwift(documentFor(fixtureIR()), DIGEST);
  const codecs = files[2];
  if (codecs === undefined) {
    throw new Error("missing codecs file");
  }
  assert.ok(codecs.contents.startsWith("// Generated by execspec. DO NOT EDIT.\n\nimport ExecSpecRuntime\n"));
  assert.ok(codecs.contents.includes(`func decodeGetResult(_ value: JSONValue) throws -> GetResult {`));
  assert.ok(codecs.contents.includes(`        return .found(try decodeValue_string(rawFound))`));
  assert.ok(codecs.contents.includes(`        return .object(["$case": .string("found"), "value": try encodeValue_string(payload)])`));
  assert.ok(codecs.contents.includes(`func decodeValue_int64(_ value: JSONValue) throws -> Int64 {`));
  assert.ok(codecs.contents.includes(`func decodeValue_list_of_list_of_int64(_ value: JSONValue) throws -> [[Int64]] {`));
  assert.ok(codecs.contents.includes(`func decodeValue_list_of_GetResult(_ value: JSONValue) throws -> [GetResult] {`));
});

test("dispatcher embeds the digest and only plumbing", () => {
  const files = generateSwift(documentFor(fixtureIR()), DIGEST);
  const dispatcher = files[3];
  if (dispatcher === undefined) {
    throw new Error("missing dispatcher file");
  }
  assert.ok(dispatcher.contents.includes(`public struct KVExecSpecDispatcher<Implementation: KVSpecificationImplementation>: ExecSpecDispatcher {`));
  assert.ok(dispatcher.contents.includes(`        self.specificationDigest = "${DIGEST}"`));
  assert.ok(dispatcher.contents.includes(`        case "kv.put":
            let requestKvPut = try decodePutRequest(input)
            let output = try await implementation.kvPut(requestKvPut)
            return try encodeValue_unit(output)`));
  assert.ok(dispatcher.contents.includes(`            throw ExecSpecHostFailure.invalidRequest("unknown operation: \\(operation)")`));
});

test("generation is deterministic and order-insensitive", () => {
  const first = generateSwift(documentFor(fixtureIR("forward")), DIGEST);
  const second = generateSwift(documentFor(fixtureIR("forward")), DIGEST);
  const reversed = generateSwift(documentFor(fixtureIR("reverse")), DIGEST);
  assert.deepEqual(first, second);
  assert.deepEqual(first, reversed);
});

test("generation refuses invalid IR", () => {
  const good = fixtureIR();
  const duplicated = good.types[0];
  if (duplicated === undefined) {
    throw new Error("fixture type missing");
  }
  const bad: SemanticIR = { ...good, types: [...good.types, duplicated] };
  assert.throws(() => generateSwift(documentFor(bad), DIGEST), /invalid IR/);
});
