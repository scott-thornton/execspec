/** generateJava: SemanticIRDocument → deterministic Java sources. */

import { compareByCodePoint, validateSemanticIR } from "@execspec/core";
import type { OperationIR, SemanticIRDocument, TypeDeclaration } from "@execspec/core";
import { emitJavaTypes } from "./emit.js";
import { emitJavaCodecs } from "./emit-codecs.js";
import { emitJavaDispatcher, emitJavaImplementationProtocol } from "./emit-dispatcher.js";

export interface GeneratedJavaFile {
  readonly relativePath: string;
  readonly contents: string;
}

const HEADER = "// Generated by execspec. DO NOT EDIT.\n";

export function generateJava(
  document: SemanticIRDocument,
  digest: string,
): readonly GeneratedJavaFile[] {
  if (document.format !== "execspec" || document.irVersion !== 1) {
    throw new Error(`unsupported IR document`);
  }
  const diagnostics = validateSemanticIR(document.semantic);
  if (diagnostics.length > 0) {
    const first = diagnostics[0];
    throw new Error(`refusing to generate Java from invalid IR: ${first?.scope}: ${first?.message}`);
  }

  const byId = <T extends { readonly id: string }>(items: readonly T[]): readonly T[] =>
    [...items].sort((l, r) => compareByCodePoint(l.id, r.id));
  const types = byId(document.semantic.types as readonly { id: string }[]) as readonly TypeDeclaration[];
  const operations = byId(document.semantic.operations) as readonly OperationIR[];
  const ir = { ...document.semantic, types, operations };

  const javaPackage = "com.execspec.generated";
  const pkgLine = `package ${javaPackage};\n\n`;
  const imports = `import com.execspec.runtime.*;\nimport java.util.*;\n\n`;

  return [
    {
      relativePath: "ExecSpecTypes.java",
      contents: `${HEADER}\n${pkgLine}${imports}${emitJavaTypes(types)}`,
    },
    {
      relativePath: "ExecSpecImplementation.java",
      contents: `${HEADER}\n${pkgLine}${imports}${emitJavaImplementationProtocol(ir, operations)}`,
    },
    {
      relativePath: "ExecSpecCodecs.java",
      contents: `${HEADER}\n${pkgLine}${imports}public final class ExecSpecCodecs {\n${emitJavaCodecs(ir)}\n}\n`,
    },
    {
      relativePath: "ExecSpecDispatcher.java",
      contents: `${HEADER}\n${pkgLine}${imports}${emitJavaDispatcher(ir, digest, operations)}`,
    },
  ];
}
