test("test command runs scenarios and exits by conformance", async () => {
  const work = await mkdtemp(join(tmpdir(), "execspec-cli-"));
  const ir = join(work, "kv.execspec.json");
  await runCli(["compile", "--module", join(fixtures, "spec-module.mjs"), "--out", ir], bufferedIO().io);

  const good = bufferedIO();
  assert.equal(
    await runCli([
      "test",
      "--ir",
      ir,
      "--host",
      join(fixtures, "echo-host.mjs"),
      "--timeout-ms",
      "5000",
    ], good.io),
    0,
  );
  assert.match(good.out(), /PASS kv\.echo\.roundtrip/);
  assert.match(good.out(), /1 passed, 0 failed/);

  const badHost = join(fixtures, "does-not-exist.mjs");
  const bad = bufferedIO();
  assert.equal(await runCli(["test", "--ir", ir, "--host", badHost], bad.io), 1);

  const badTimeout = bufferedIO();
  assert.equal(await runCli(["test", "--ir", ir, "--host", join(fixtures, "echo-host.mjs"), "--timeout-ms", "0"], badTimeout.io), 2);
});

test("spawned CLI binary behaves identically", async () => {
  const work = await mkdtemp(join(tmpdir(), "execspec-cli-"));
  const out = join(work, "kv.execspec.json");
  const entry = resolve(dirname(fileURLToPath(import.meta.url)), "../../dist/index.js");
  const code = await new Promise<number>((resolveCode, reject) => {
    execFile(
      process.execPath,
      [entry, "compile", "--module", join(fixtures, "spec-module.mjs"), "--out", out],
      (error, stdout) => {
        if (error !== null && error.code !== 0) {
          reject(error);
          return;
        }
        assert.match(stdout, /^[0-9a-f]{64}\n$/);
        resolveCode(0);
      },
    );
  });
  assert.equal(code, 0);
});

test("test command supports --scenario filtering and --concurrency", async () => {
  const work = await mkdtemp(join(tmpdir(), "execspec-cli-"));
  const ir = join(work, "kv.execspec.json");
  await runCli(["compile", "--module", join(fixtures, "spec-module.mjs"), "--out", ir], bufferedIO().io);

  const filtered = bufferedIO();
  assert.equal(
    await runCli(["test", "--ir", ir, "--host", join(fixtures, "echo-host.mjs"), "--scenario", "roundtrip"], filtered.io),
    0,
  );
  assert.match(filtered.out(), /PASS kv\.echo\.roundtrip/);
  assert.doesNotMatch(filtered.out(), /PASS kv\.other/);
  assert.match(filtered.out(), /1 passed, 0 failed/);

  const noMatch = bufferedIO();
  assert.equal(
    await runCli(["test", "--ir", ir, "--host", join(fixtures, "echo-host.mjs"), "--scenario", "nope"], noMatch.io),
    0,
  );
  assert.match(noMatch.out(), /0 passed, 0 failed/);

  const badConcurrency = bufferedIO();
  assert.equal(
    await runCli(["test", "--ir", ir, "--host", join(fixtures, "echo-host.mjs"), "--concurrency", "0"], badConcurrency.io),
    2,
  );
});

test("init scaffolds a self-contained specification package", async () => {
  const work = await mkdtemp(join(tmpdir(), "execspec-init-"));
  const io = bufferedIO();
  assert.equal(await runCli(["init", "--name", "acme-contract", "--out", work], io.io), 0);
  assert.match(io.out(), /npm install && npm test/);
  const pkg = JSON.parse(await readFile(join(work, "package.json"), "utf8")) as {
    name: string; scripts: Record<string, string>; dependencies: Record<string, string>;
  };
  assert.equal(pkg.name, "acme-contract");
  assert.equal(pkg.dependencies["@execspec/dsl"], "^0.3.0");
  for (const file of ["tsconfig.json", "tsconfig.test.json", "README.md", "src/spec.ts", "test/spec.test.ts"]) {
    await readFile(join(work, file), "utf8");
  }
  const spec = await readFile(join(work, "src/spec.ts"), "utf8");
  assert.match(spec, /spec\.operation\(operation\("demo\.echo"/);
  assert.equal(await runCli(["init", "--name", "Bad Name", "--out", join(work, "x")], bufferedIO().io), 2);
});
