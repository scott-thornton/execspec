test("generate swift writes the four files and replaces the directory atomically", async () => {
  const work = await mkdtemp(join(tmpdir(), "execspec-cli-"));
  const ir = join(work, "kv.execspec.json");
  const compileIO = bufferedIO();
  await runCli(["compile", "--module", join(fixtures, "spec-module.mjs"), "--out", ir], compileIO.io);

  const out = join(work, "KVGenerated");
  await mkdir(out, { recursive: true });
  await writeFile(join(out, "stale.swift"), "// stale\n", "utf8");

  const io = bufferedIO();
  const code = await runCli(["generate", "swift", "--ir", ir, "--out", out], io.io);
  assert.equal(code, 0);
  assert.deepEqual((await readdir(out)).sort(), [
    "ExecSpecCodecs.swift",
    "ExecSpecDispatcher.swift",
    "ExecSpecImplementation.swift",
    "ExecSpecTypes.swift",
  ]);
  const types = await readFile(join(out, "ExecSpecTypes.swift"), "utf8");
  assert.ok(types.startsWith("// Generated by execspec. DO NOT EDIT.\n"));
  const dispatcher = await readFile(join(out, "ExecSpecDispatcher.swift"), "utf8");
  assert.ok(dispatcher.includes(compileIO.out().trim()));
});

