import { test } from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import { mkdtemp, readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { execFile } from "node:child_process";

import { runCli } from "../src/index.js";
import type { CliIO } from "../src/index.js";

const fixtures = join(dirname(fileURLToPath(import.meta.url)), "fixtures");

function bufferedIO(): { io: CliIO; out(): string; err(): string } {
  let outText = "";
  let errText = "";
  return {
    io: {
      writeOut(text: string): void {
        outText += text;
      },
      writeErr(text: string): void {
        errText += text;
      },
    },
    out: () => outText,
    err: () => errText,
  };
}

test("unknown commands and missing flags exit 2", async () => {
  const unknown = bufferedIO();
  assert.equal(await runCli(["frobnicate"], unknown.io), 2);
  assert.match(unknown.err(), /unknown command/);

  const noArgs = bufferedIO();
  assert.equal(await runCli([], noArgs.io), 2);

  const missingFlags = bufferedIO();
  assert.equal(await runCli(["compile", "--module", "x"], missingFlags.io), 2);
  assert.match(missingFlags.err(), /--out/);

  const badGenerate = bufferedIO();
  assert.equal(await runCli(["generate", "rust"], badGenerate.io), 2);
});

test("compile writes canonical IR and prints the digest", async () => {
  const work = await mkdtemp(join(tmpdir(), "execspec-cli-"));
  const out = join(work, "kv.execspec.json");
  const io = bufferedIO();
  const code = await runCli(["compile", "--module", join(fixtures, "spec-module.mjs"), "--out", out], io.io);
  assert.equal(code, 0);
  const digest = io.out().trim();
  assert.match(digest, /^[0-9a-f]{64}$/);

  const contents = await readFile(out, "utf8");
  assert.ok(contents.endsWith("\n"), "written file has exactly one trailing LF");
  assert.equal(contents.indexOf("\n"), contents.length - 1, "canonical JSON is one line");
  const parsed: unknown = JSON.parse(contents);
  const record = parsed as { format?: string; irVersion?: number };
  assert.equal(record.format, "execspec");
  assert.equal(record.irVersion, 1);
});

test("compile determinism: same module, same digest and bytes", async () => {
  const work = await mkdtemp(join(tmpdir(), "execspec-cli-"));
  const first = join(work, "a.json");
  const second = join(work, "b.json");
  const ioA = bufferedIO();
  const ioB = bufferedIO();
  await runCli(["compile", "--module", join(fixtures, "spec-module.mjs"), "--out", first], ioA.io);
  await runCli(["compile", "--module", join(fixtures, "spec-module.mjs"), "--out", second], ioB.io);
  assert.equal(ioA.out(), ioB.out());
  assert.equal(await readFile(first, "utf8"), await readFile(second, "utf8"));
});

